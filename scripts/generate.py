"""Generate src/bloklake/fields.py from scripts/schema.json (a copy of GET /v1/schema).

Run `python scripts/generate.py` after refreshing schema.json when the API adds fields.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
schema = json.loads((ROOT / "scripts" / "schema.json").read_text())


def camel_case(name: str) -> str:
    """``block_number`` -> ``blockNumber``; must match ``bloklake.client._camel``."""
    return re.sub(r"_([a-z0-9])", lambda m: m.group(1).upper(), name)


# Requests may name a field by its column name (``block_number``); the client turns it into the
# request name. That only works while every request name is its column name in camelCase.
for rt, fs in schema["row_types"].items():
    for f in fs:
        if camel_case(f["name"]) != f["dsl_name"]:
            raise SystemExit(f'{rt}.{f["name"]}: request name {f["dsl_name"]} is not the column name in camelCase')

# uint256 amounts: 32 bytes like a hash, but decimal strings in JSON (the server's catalogue)
UINT256 = ["max_refund", "submission_fee_refund", "deposit_value", "retry_value", "max_submission_fee", "l1_base_fee"]
STRUCT_NAMES = {"withdrawals": "Withdrawal", "access_list": "AccessListEntry", "authorization_list": "Authorization"}
structs: dict[str, str] = {}


def parse(s: str):
    pos = 0

    def ws():
        nonlocal pos
        while pos < len(s) and s[pos] == " ":
            pos += 1

    def ident():
        nonlocal pos
        m = re.match(r"[A-Za-z0-9_]+", s[pos:])
        pos += len(m.group(0))
        return m.group(0)

    def typ():
        nonlocal pos
        ws()
        name = ident()
        if name == "FixedSizeBinary":
            pos += 1; n = ident(); pos += 1
            return ("fsb", int(n))
        if name == "List":
            pos += 1; t = typ(); pos += 1
            return ("list", t)
        if name == "Struct":
            pos += 1; fields = []
            while True:
                ws(); n = ident(); ws(); pos += 1; t = typ(); fields.append((n, t)); ws()
                if s[pos] == ",":
                    pos += 1; continue
                pos += 1; break
            return ("struct", fields)
        return ("prim", name)

    return typ()


def py_type(t, column: str) -> str:
    kind = t[0]
    if kind == "prim":
        return "int" if t[1].startswith("UInt") else "str"
    if kind == "fsb":
        return "str"
    if kind == "list":
        return f"List[{py_type(t[1], column)}]"
    name = STRUCT_NAMES.get(column, f"{column}_entry")
    if name not in structs:
        body = ", ".join(f'"{n}": {py_type(ft, n)}' for n, ft in t[1])
        structs[name] = f'{name} = TypedDict("{name}", {{{body}}})'
    return name


out = ['"""Generated by scripts/generate.py from scripts/schema.json (GET /v1/schema). Do not edit."""',
       "from typing import FrozenSet, List, Literal, Mapping, Optional, TypedDict", ""]
rows = []
for key, field_alias, row in (("logs", "LogField", "Log"), ("transactions", "TransactionField", "Transaction"), ("blocks", "BlockField", "Block")):
    fields = schema["row_types"][key]
    names = [f["dsl_name"] for f in fields] + (["topics"] if key == "logs" else [])
    # The same fields by column name, for snake_case requests (``block_number``).
    names += [f["name"] for f in fields if f["name"] != f["dsl_name"]]
    rows.append(f"{field_alias} = Literal[\n" + "".join(f'    "{n}",\n' for n in names) + "]")
    rows.append(f'"""Field names for `fields.{ {"logs": "log", "transactions": "transaction", "blocks": "block"}[key] }`: '
                f'the request name (camelCase) or the column name (snake_case)."""')
    rows.append("")
    entries = []
    for f in fields:
        t = py_type(parse(f["arrow_type"]), f["name"])
        if f["nullable"]:
            t = f"Optional[{t}]"
        entries.append(f'        "{f["name"]}": {t},  # {f["arrow_type"]}')
    rows.append(f'{row} = TypedDict(\n    "{row}",\n    {{\n' + "\n".join(entries) + "\n    },\n    total=False,\n)")
    rows.append(f'"""A {key[:-1]} row: keys are present only for the fields you selected."""')
    rows.append("")
out += list(structs.values()) + [""] + rows
out.append("UINT256_COLUMNS: Mapping[str, FrozenSet[str]] = {")
out.append(f'    "transactions": frozenset({sorted(UINT256)!r}),')
out.append("}")
out.append('"""Response keys that hold uint256 amounts (decimal strings), per row type."""')
(ROOT / "src" / "bloklake" / "fields.py").write_text("\n".join(out) + "\n")
print("wrote src/bloklake/fields.py")
